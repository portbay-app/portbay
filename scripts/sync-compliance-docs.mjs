#!/usr/bin/env node
// Publish the canonical compliance/legal docs into the VitePress site.
//
// The legal + security docs are authored ONCE, in their canonical homes
// (docs/, and SECURITY.md / THIRD-PARTY-MODELS.md at the repo root — where the
// Trust Center, tests, and GitHub's security tab reference them). The public
// docs site builds from docs-site/, so without this step docs.portbay.app has
// no /legal, /security, or /accessibility pages and every Trust Center link
// 404s. Rather than keep a second, divergable copy in git, this script copies
// them into docs-site/ at build time (the copies are gitignored) and rewrites
// their internal markdown links so they resolve on the published site:
//   - a link to another PUBLISHED doc  -> its clean docs.portbay.app path
//   - any other repo-relative link     -> an absolute github.com/blob URL
// External (http/mailto) links and in-page #anchors are left untouched.
//
// Run automatically before `docs:build` / `docs:dev` (see package.json
// pre-scripts). The generated files are gitignored; edit the canonical source.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import posix from "node:path/posix";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..");

const GH = "https://github.com/portbay-app/portbay";

// Canonical repo-relative source -> destination under docs-site/.
const SYNC = [
  ["docs/legal/privacy-policy.md", "docs-site/legal/privacy-policy.md"],
  ["docs/legal/terms-of-service.md", "docs-site/legal/terms-of-service.md"],
  ["docs/security/whitepaper.md", "docs-site/security/whitepaper.md"],
  ["docs/security/vendor-faq.md", "docs-site/security/vendor-faq.md"],
  ["docs/accessibility.md", "docs-site/accessibility.md"],
  ["SECURITY.md", "docs-site/security/policy.md"],
  ["THIRD-PARTY-MODELS.md", "docs-site/security/model-manifest.md"],
];

// Canonical repo-relative source -> its clean published URL (cleanUrls: true,
// so no .md/.html). Keyed by the SAME path used as a link target's resolution.
const PUBLISHED = {
  "docs/legal/privacy-policy.md": "/legal/privacy-policy",
  "docs/legal/terms-of-service.md": "/legal/terms-of-service",
  "docs/security/whitepaper.md": "/security/whitepaper",
  "docs/security/vendor-faq.md": "/security/vendor-faq",
  "docs/accessibility.md": "/accessibility",
  "SECURITY.md": "/security/policy",
  "THIRD-PARTY-MODELS.md": "/security/model-manifest",
};

/** Split a link target into [path, "#anchor"] (anchor keeps its leading #). */
function splitAnchor(target) {
  const i = target.indexOf("#");
  return i === -1 ? [target, ""] : [target.slice(0, i), target.slice(i)];
}

/** Rewrite one link target found in `sourceRel` (its repo-relative path). */
function rewriteTarget(target, sourceRel) {
  const trimmed = target.trim();
  // Leave external links and pure in-page anchors alone.
  if (/^(https?:|mailto:|tel:|\/\/)/i.test(trimmed)) return target;
  if (trimmed.startsWith("#")) return target;

  const [pathPart, anchor] = splitAnchor(trimmed);
  const srcDir = posix.dirname(sourceRel);
  const isDir = pathPart.endsWith("/");
  const resolved = posix.normalize(posix.join(srcDir, pathPart));

  const onsite = PUBLISHED[resolved];
  if (onsite) return onsite + anchor;

  if (isDir) {
    return `${GH}/tree/main/${resolved.replace(/\/$/, "")}${anchor}`;
  }
  return `${GH}/blob/main/${resolved}${anchor}`;
}

/** Rewrite every inline markdown link `](target)` in the doc body. */
function rewriteLinks(body, sourceRel) {
  return body.replace(/\]\(([^)]+)\)/g, (whole, inner) => {
    // inner may be `target` or `target "title"`; only touch the target.
    const m = inner.match(/^(\s*)(\S+)(\s+.*)?$/);
    if (!m) return whole;
    const [, lead, urlTok, rest = ""] = m;
    return `](${lead}${rewriteTarget(urlTok, sourceRel)}${rest})`;
  });
}

const GENERATED_BANNER =
  "<!-- GENERATED by scripts/sync-compliance-docs.mjs from ";

let wrote = 0;
for (const [srcRel, destRel] of SYNC) {
  const srcAbs = resolve(ROOT, srcRel);
  const destAbs = resolve(ROOT, destRel);
  let body;
  try {
    body = readFileSync(srcAbs, "utf8");
  } catch (e) {
    console.error(`sync-compliance-docs: cannot read ${srcRel}: ${e.message}`);
    process.exit(1);
  }
  const rewritten = `${GENERATED_BANNER}${srcRel} — edit the source, not this copy. -->\n${rewriteLinks(body, srcRel)}`;
  mkdirSync(dirname(destAbs), { recursive: true });
  writeFileSync(destAbs, rewritten);
  console.log(`sync-compliance-docs: ${srcRel} -> ${destRel}`);
  wrote += 1;
}
console.log(`sync-compliance-docs: published ${wrote} docs into docs-site/.`);
